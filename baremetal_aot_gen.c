#include<stdio.h>

unsigned char img[131072];
int pos=512;
int stack[1024];
int sp=0;

void E(unsigned char b){ img[pos++]=b; }
void E2(unsigned char a,unsigned char b){ E(a); E(b); }
void E3(unsigned char a,unsigned char b,unsigned char c){ E(a); E(b); E(c); }

int main(){
    unsigned char boot[]={
        0xFA,0x31,0xC0,0x8E,0xD8,0x8E,0xC0,0x8E,0xD0,0xBC,0x00,0x7C,0xB4,0x02,0xB0,0x3E,
        0xB5,0x00,0xB1,0x02,0xB6,0x00,0xBB,0x00,0x7E,0xCD,0x13,0xEA,0x00,0x7E,0x00,0x00
    };
    for(int i=0;i<32;i++) img[i]=boot[i];
    img[510]=0x55;
    img[511]=0xAA;

    // build_pure_s1.py と一致させる
    E(0xFA);                // cli
    E(0xFC);                // cld
    E2(0x31,0xC0);          // xor ax,ax
    E2(0x8E,0xC0);          // mov es,ax
    E2(0x8E,0xD8);          // mov ds,ax

    // クリア範囲も合わせる
    E3(0xBF,0x00,0x10);      // mov di,0x1000
    E3(0xB9,0xFF,0x7F);      // mov cx,0x7FFF
    E2(0x31,0xC0);
    E2(0xF3,0xAB);          // rep stosw

    E3(0xBF,0x00,0x00);      // mov si,0x0000
    E3(0xBB,0x00,0x10);      // mov bx,0x1000

    E3(0xBA,0xFB,0x03); E2(0xB0,0x80); E(0xEE);
    E3(0xBA,0xF8,0x03); E2(0xB0,0x01); E(0xEE);
    E3(0xBA,0xF9,0x03); E2(0xB0,0x00); E(0xEE);
    E3(0xBA,0xFB,0x03); E2(0xB0,0x03); E(0xEE);
    E3(0xBA,0xFA,0x03); E2(0xB0,0x01); E(0xEE);

    // FIFO enable
    E3(0xBA,0xFC,0x03);
    E2(0xB0,0xC7);
    E(0xEE);

    // modem control
    E3(0xBA,0xFE,0x03);
    E2(0xB0,0x0B);
    E(0xEE);

    int c;
    while((c=getchar())!=EOF){
        if(c=='1') E(0x47);
        if(c=='2') E(0x4F);
        if(c=='3') E2(0xFE,0x05);
        if(c=='4') E2(0xFE,0x0D);
        if(c=='5'){
            E3(0xBA,0xFD,0x03);
            E(0xEC);
            E2(0xA8,0x01);
            E2(0x74,0xF8);
            E3(0xBA,0xF8,0x03);
            E(0xEC);
            E2(0x88,0x07);
        }
        if(c=='6'){
            E3(0xBA,0xFD,0x03);
            E(0xEC);
            E2(0xA8,0x20);
            E2(0x74,0xF8);
            E3(0xBA,0xF8,0x03);
            E2(0x8A,0x07);
            E(0xEE);
        }
        if(c=='7'){
            int b=pos;
            E3(0x80,0x3D,0x00);
            E2(0x0F,0x84);
            stack[sp++]=pos;
            E2(0x00,0x00);
            stack[sp++]=b;
        }
        if(c=='8'){
            E3(0x80,0x3D,0x00);
            E2(0x0F,0x85);
            int b=stack[--sp];
            int f=stack[--sp];
            int off=b-(pos+2);
            E(off&0xFF);
            E((off>>8)&0xFF);
            int fwd=pos-(f+2);
            img[f]=fwd&0xFF;
            img[f+1]=(fwd>>8)&0xFF;
        }
        if(c=='9') E3(0x80,0x05,0x03);
        if(c=='a') E3(0x80,0x2D,0x03);
    }

    E2(0xFA,0xF4);
    E2(0xEB,0xFD);

    int target_size = 63 * 512;
    int final_size = (pos > target_size) ? ((pos + 511) / 512) * 512 : target_size;

    FILE *out=fopen("void_os.img","wb");
    fwrite(img,1,final_size,out);
    fclose(out);
    return 0;
}
